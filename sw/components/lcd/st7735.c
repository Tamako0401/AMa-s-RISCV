#include "lcd.h"

#include "lcd_io.h"

/* 写周期最短 66ns, 即 15 MHz; 50 MHz 下实际分到 12.5 MHz */
#define ST7735_MAX_HZ 15000000UL

/* 1.8 寸 128x160 ST7735S 模块常见的厂商初始化序列。
 * 颜色若红蓝互换, 把 MADCTL 的 0xC0 改成 0xC8 (BGR 位)。 */
static const uint8_t st7735_seq[] = {
    0x11, LCD_SEQ_DELAY,
    120, /* SLPOUT 退出睡眠 */
    0xB1, 3,
    0x05, 0x3C,
    0x3C, /* 帧率: 正常模式 */
    0xB2, 3,
    0x05, 0x3C,
    0x3C, /* 帧率: 空闲模式 */
    0xB3, 6,
    0x05, 0x3C,
    0x3C, 0x05,
    0x3C, 0x3C, /* 帧率: 局部模式 */
    0xB4, 1,
    0x03, /* 点反转 */
    0xC0, 3,
    0x28, 0x08,
    0x04, /* 电源控制 */
    0xC1, 1,
    0xC0, 0xC2,
    2,    0x0D,
    0x00, 0xC3,
    2,    0x8D,
    0x2A, 0xC4,
    2,    0x8D,
    0xEE, 0xC5,
    1,    0x1A, /* VCOM */
    0x36, 1,
    0xC0, /* MADCTL 竖屏, 从左上开始, RGB */
    0xE0, 16,
    0x04, 0x22,
    0x07, 0x0A,
    0x2E, 0x30,
    0x25, 0x2A,
    0x28, 0x26,
    0x2E, 0x3A,
    0x00, 0x01,
    0x03, 0x13, /* 正 gamma */
    0xE1, 16,
    0x04, 0x16,
    0x06, 0x0D,
    0x2D, 0x26,
    0x23, 0x27,
    0x27, 0x25,
    0x2D, 0x3B,
    0x00, 0x01,
    0x04, 0x13, /* 负 gamma */
    0x3A, 1,
    0x05, /* COLMOD 16 位 RGB565 */
    0x29, LCD_SEQ_DELAY,
    100, /* DISPON 打开显示 */
};

void lcd_init_st7735(const lcd_pins_t *pins)
{
    lcd_io_init(pins, 0, ST7735_MAX_HZ); /* 模式 0: 空闲低, 上升沿采样 */
    lcd_w = 128;
    lcd_h = 160;
    lcd_reset();
    lcd_run_seq(st7735_seq, sizeof(st7735_seq));
}
