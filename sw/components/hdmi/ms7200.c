static const uint16_t enable_seq[][2] = {{0x000C, 0x00}, {0x000A, 0x04}, {0x2000, 0x0F},
                                         {0x2001, 0x00}, {0x2002, 0x00}, {0x2003, 0x01}};
static const uint16_t lock_seq[][2] = {{0x1010, 0x01}, {0x1024, 0x00}, {0x0200, 0x00}, {0x1024, 0x70},
                                       {0x0200, 0x07}, {0x0215, 0x01}, {0x0215, 0x00}};

static int write_all(const i2c_pins_t *i2c, const uint16_t (*seq)[2], uint32_t n)
{
    for (uint32_t i = 0; i < n; i++)
        if (reg_write(i2c, seq[i][0], seq[i][1]))
            return -1;
    return 0;
}

int ms7200_init(const i2c_pins_t *i2c)
{
    /* 先写一个寄存器再读回, 确认芯片在 */
    uint8_t id = 0;
    if (reg_write(i2c, 0x0003, 0x5A) || reg_read(i2c, 0x0003, &id) || id != 0x5A)
        return -1;
    if (write_all(i2c, init_seq, sizeof init_seq / sizeof init_seq[0]))
        return -1;
    for (uint32_t i = 0; i < sizeof edid; i++)
        if (reg_write(i2c, 0x0D00 + i, edid[i]))
            return -1;
    return write_all(i2c, enable_seq, sizeof enable_seq / sizeof enable_seq[0]);
}

int ms7200_poll(const i2c_pins_t *i2c)
{
    /* 0x209C~0x209F 是输入时钟测量, 按例程依次读; 0x209E 低 2 位从 00 变成 10 表示时钟刚稳定 */
    static uint8_t last;
    uint8_t status[4];
    for (uint32_t i = 0; i < 4; i++)
        if (reg_read(i2c, 0x209C + i, &status[i]))
            return 0;
    uint8_t now = status[2] & 3;
    int locked = (last & 3) == 0 && now == 2;
    last = now;
    if (locked)
        write_all(i2c, lock_seq, sizeof lock_seq / sizeof lock_seq[0]);
    return locked;
}
