#include "ms7210.h"
#include "bsp.h"
#include "io.h"

#define DEV 0xB2 /* SA 脚上拉 (MES50HP 硬件手册 3.3.2) */

/* 寄存器表抄自盘古 50K 例程 05_hdmi_test/src/ms7210_ctl.v (RGB888 输入, 自动识别分辨率);
 * 两段之间要等约 0.3 秒, 同例程。 */
static const uint16_t init_seq[][2] = {
    {0x1281, 0x04}, {0x0016, 0x04}, {0x0009, 0x01}, {0x0007, 0x09}, {0x0008, 0xF0}, {0x000A, 0xF0}, {0x0006, 0x11},
    {0x0531, 0x84}, {0x0900, 0x20}, {0x0901, 0x47}, {0x0904, 0x09}, {0x0923, 0x07}, {0x0924, 0x44}, {0x0925, 0x44},
    {0x090F, 0x80}, {0x091F, 0x07}, {0x0920, 0x1E}, {0x0018, 0x20}, {0x05C0, 0xFE},
};
static const uint16_t setting_seq[][2] = {
    {0x000B, 0x00}, {0x0507, 0x06}, {0x0906, 0x04}, {0x0920, 0x5E}, {0x0926, 0xDD}, {0x0927, 0x0D},
    {0x0928, 0x88}, {0x0929, 0x08}, {0x0910, 0x01}, {0x000B, 0x11}, {0x050E, 0x00}, {0x050A, 0x82},
    {0x0509, 0x02}, {0x050B, 0x0D}, {0x050D, 0x06}, {0x050D, 0x11}, {0x050D, 0x58}, {0x050D, 0x00},
    {0x050D, 0x00}, {0x050D, 0x00}, {0x050D, 0x00}, {0x050D, 0x00}, {0x050D, 0x00}, {0x050D, 0x00},
    {0x050D, 0x00}, {0x050D, 0x00}, {0x050D, 0x00}, {0x050D, 0x00}, {0x050E, 0x40}, {0x0507, 0x00},
};

static int write_all(const i2c_pins_t *i2c, const uint16_t (*seq)[2], uint32_t n)
{
    for (uint32_t i = 0; i < n; i++)
        if (i2c_write_reg16(i2c, DEV, seq[i][0], seq[i][1]))
            return -1;
    return 0;
}

int ms7210_init(const ms7210_pins_t *pins)
{
    io_write(pins->rst, 0);
    io_dir(pins->rst, IO_OUTPUT);
    i2c_init(&pins->i2c);
    delay_ms(1);
    io_write(pins->rst, 1);
    delay_ms(1);

    /* 先写一个寄存器再读回, 确认芯片在 */
    uint8_t id = 0;
    if (i2c_write_reg16(&pins->i2c, DEV, 0x0003, 0x5A) || i2c_read_reg16(&pins->i2c, DEV, 0x0003, &id) || id != 0x5A)
        return -1;
    if (write_all(&pins->i2c, init_seq, sizeof init_seq / sizeof init_seq[0]))
        return -1;
    delay_ms(300);
    return write_all(&pins->i2c, setting_seq, sizeof setting_seq / sizeof setting_seq[0]);
}
